/**
 * 每次从 20 道大河文明题库中随机洗牌抽取指定数量（默认 7 道）题目
 */
export function getRandomQuizQuestions(count: number = 7): QuizQuestion[] {
  const pool = [...CHONGQING_CULTURE_QUIZ_POOL];
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    const temp = pool[i];
    pool[i] = pool[j];
    pool[j] = temp;
  }
  return pool.slice(0, Math.min(count, pool.length));
}

